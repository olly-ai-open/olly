#!/usr/bin/env node
/**
 * Build the env file that gets bundled into the packaged desktop app.
 *
 * The dev `apps/web/.env.local` holds OAuth client creds + NEXTAUTH_SECRET
 * (which the packaged app needs) AND the developer's own LLM API keys (which
 * it must NOT ship). Bundling the LLM keys would (a) leak live secrets inside
 * every DMG/EXE and (b) suppress the first-run /setup flow, since the app
 * decides setup is complete whenever an LLM key is present in the environment.
 *
 * This script copies `.env.local` -> `.env.packaged.local`, stripping the LLM
 * keys (including commented-out ones, which still embed a real key string).
 * `electron-builder` then bundles the sanitized file as `env/.env.local`.
 *
 * The `.local` suffix keeps the generated file matched by `.gitignore`.
 */

const fs = require("node:fs");
const path = require("node:path");

const repoRoot = path.resolve(__dirname, "..", "..");
const webDir = path.join(repoRoot, "apps", "web");
const srcEnv = path.join(webDir, ".env.local");
const outEnv = path.join(webDir, ".env.packaged.local");

// Keys that must NEVER ship inside the installer.
//
// Three buckets:
//   1. LLM keys — the user supplies these via first-run /setup, and bundling
//      one also suppresses the setup gate.
//   2. Notion app creds — Notion is now a per-user token paste, so the old
//      app-level OAuth creds (incl. a real secret) are obsolete.
//   3. Telemetry + hosted-backend creds — the desktop build is local-only and
//      must not phone home. The packaged app always uses embedded Postgres
//      (electron/main.js `ensureDatabase` ignores DATABASE_URL when packaged),
//      so the hosted DB URLs are unused at runtime AND would otherwise leak a
//      production Supabase connection string in plaintext inside every DMG/EXE.
//      With the Langfuse keys gone, `canEnable()` is false and tracing no-ops.
const STRIP_KEYS = [
  // (1) LLM keys — user supplies their own via first-run /setup
  "OPENAI_API_KEY",
  "ANTHROPIC_API_KEY",
  "GEMINI_API_KEY",
  "LLM_PROVIDER",
  // (2) Notion app creds (now a per-user token paste)
  "NOTION_CLIENT_ID",
  "NOTION_CLIENT_SECRET",
  // (2) Jira — these are a developer's PERSONAL Jira account creds, not app-level
  "JIRA_API_TOKEN",
  "JIRA_EMAIL",
  "JIRA_BASE_URL",
  // (3) Telemetry — must not send user data to our servers
  "LANGFUSE_PUBLIC_KEY",
  "LANGFUSE_SECRET_KEY",
  "LANGFUSE_BASE_URL",
  "NEW_RELIC_LICENSE_KEY",
  "NEW_RELIC_APP_NAME",
  // (3) Debug capture — flag + our S3 bucket name; desktop must not upload debug data
  "ENABLE_DEBUG_CAPTURE",
  "S3_DEBUG_BUCKET",
  // (3) Hosted backend DB — desktop uses embedded Postgres; never ship prod creds
  "DATABASE_URL",
  "PRISMA_DATABASE_URL",
  "DIRECT_URL",
  "SUPABASE_URL",
  "SUPABASE_ANON_KEY",
  // (4) Per-install secrets — the desktop app generates its own session secret
  //     and field encryption key on first launch (electron/lib/state.js), so
  //     the builder's values must not ship and be shared by every install.
  "AUTH_SECRET",
  "NEXTAUTH_SECRET",
  "PRISMA_FIELD_ENCRYPTION_KEY",
  // (5) Web push — Electron has no push service, so the keys are useless on
  //     desktop and the private key must not ship.
  "VAPID_PRIVATE_KEY",
  "VAPID_PUBLIC_KEY",
  "NEXT_PUBLIC_VAPID_PUBLIC_KEY",
  "VAPID_SUBJECT",
];

function keyOfLine(line) {
  // Match `KEY=...` or commented `#KEY=...` (with optional surrounding space).
  const m = line.match(/^\s*#?\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/);
  return m ? m[1] : null;
}

if (!fs.existsSync(srcEnv)) {
  console.warn(
    `[build-packaged-env] No ${srcEnv} found; writing empty packaged env. ` +
      `The app will require first-run LLM setup, but OAuth/auth secrets will be missing.`,
  );
  fs.writeFileSync(outEnv, "# Generated for packaging. Source .env.local was missing.\n", "utf8");
  process.exit(0);
}

const lines = fs.readFileSync(srcEnv, "utf8").split(/\r?\n/);

const stripped = [];
const kept = lines.filter((line) => {
  const key = keyOfLine(line);
  if (key && STRIP_KEYS.includes(key)) {
    stripped.push(key);
    return false;
  }
  return true;
});

const header =
  "# AUTO-GENERATED by electron/scripts/build-packaged-env.js — do not edit.\n" +
  "# LLM keys are intentionally excluded; users provide them via first-run setup.\n";

fs.writeFileSync(outEnv, header + kept.join("\n"), "utf8");

console.log(`[build-packaged-env] wrote ${outEnv}`);
console.log(
  `[build-packaged-env] stripped LLM key lines: ${
    stripped.length ? stripped.join(", ") : "(none found)"
  }`,
);
